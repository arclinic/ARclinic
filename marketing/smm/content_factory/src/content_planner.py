import json
from pathlib import Path
from typing import Dict
from .ai_client import AIClient

def load_knowledge_base() -> str:
    kb_path = Path(__file__).parent.parent / 'knowledge_base.md'
    if kb_path.exists():
        with open(kb_path, 'r', encoding='utf-8') as f:
            return f.read()
    return ""

def generate_content_ideas(ai: AIClient, outliers_by_platform: Dict) -> str:
    knowledge_base = load_knowledge_base()
    
    system_prompt = f"""Ты — контент-стратег Анны Резник, врача-дерматолога-косметолога, владельца ARclinic (СПб).

Ты работаешь ТОЛЬКО в рамках следующей базы знаний о личности, бренде, голосе и бизнесе Анны:

{knowledge_base}

ВАЖНЫЕ ПРАВИЛА:
1. Все идеи должны соответствовать голосу Анны: экспертный, тёплый, честный, с иронией
2. Никаких агрессивных продаж — только рекомендации
3. Никаких обещаний чуда за 1 день
4. Каждый пост должен нести ценность (научпоп, разбор, ответ на вопрос)
5. Аудитория: осознанные женщины 30+, ценящие экспертность
6. Контент строится на доказательной медицине и личной экспертизе
7. ЗАПРЕЩЕНО: диагнозы без осмотра, гарантии результата, критика коллег поимённо, БАДы как панацея"""
    
    prompt = f"""На основе анализа вирусного контента конкурентов, сгенерируй 10-15 контент-идей для Анны Резник с кросс-платформенным потенциалом.

Анализ конкурентов:
{json.dumps(outliers_by_platform, indent=2, ensure_ascii=False)}

Для каждой идеи укажи:
1. Заголовок/Хук (в голосе Анны)
2. Суть идеи
3. Целевые платформы (ранжированные по соответствию)
4. Формат контента (пост-объяснение, разбор процедуры, ответ на вопрос, личная история, сравнение)
5. Ключевые углы/подходы
6. Оценочные усилия (низкие/средние/высокие)
7. Как это работает на возражения аудитории (дорого/больно/точно нужно/сделаю потом)
8. Сезонность (актуально в пик: мар-май, сен-ноя, или всегда)

Формат: markdown с чёткими секциями."""
    
    return ai.generate(prompt, system_prompt)

def generate_playbooks(ai: AIClient, outliers_by_platform: Dict) -> Dict[str, str]:
    playbooks = {}
    knowledge_base = load_knowledge_base()
    
    system_prompt = f"""Ты — эксперт по контенту для социальных платформ, работающий для бренда Анны Резник (ARclinic).

Контекст бренда:
{knowledge_base}

Правила:
- Все рекомендации адаптируй под голос Анны и аудиторию ARclinic
- Учитывай премиальный позиционирование (Средний+/Премиум, СПб)
- Фокус на доказательной медицине и личной экспертизе
- Контент должен закрывать возражения и показывать экспертизу"""
    
    platform_names = {
        'x': 'X/Twitter',
        'instagram': 'Instagram',
        'youtube': 'YouTube',
        'tiktok': 'TikTok'
    }
    
    for platform, outliers in outliers_by_platform.items():
        if not outliers:
            continue
        
        prompt = f"""Создай детальный контент-плейбук для платформы {platform_names.get(platform, platform)} на основе анализа лучших постов конкурентов:

Анализ топ-10 постов:
{json.dumps(outliers[:10], indent=2, ensure_ascii=False)}

Структурируй playbook:

1. **Тренды на платформе** — что сейчас работает
2. **Применимость для ARclinic** — какие паттерны конкурентов адаптировать под бренд Анны
3. **Оптимальное время публикаций** (на основе вовлечённости)
4. **Лучшие форматы контента** для платформы (с адаптацией под голос Анны)
5. **Стратегия хуков** — как начинать посты/видео
6. **Тактики вовлечения** — как стимулировать комментарии и сохранения
7. **Хештеги и теги** — рекомендации
8. **Call-to-action** — как приглашать без агрессивных продаж
9. **Чего избегать** — типичные ошибки в бьюти-контенте
10. **Месячный план** — 8-12 постов с темами и форматами

Формат: markdown playbook."""
        
        playbooks[platform] = ai.generate(prompt, system_prompt)
    
    return playbooks
