def analyze_keyword_density(text: str) -> list:
    """Анализирует плотность ключевых слов в тексте."""
    words = re.findall(r'\w+', text.lower())
    word_freq = Counter(words)
    
    # Фильтруем стоп-слова
    stop_words = {'и', 'в', 'на', 'с', 'по', 'для', 'не', 'а', 'но', 'от', 'о', 'об', 'к', 'у', 'за', 'из', 'до', 'при', 'без', 'через', 'после', 'это', 'что', 'как', 'все', 'или', 'если', 'так', 'же', 'даже', 'уже', 'еще', 'бы', 'ли', 'ни', 'то', 'чтобы', 'можно', 'нужно', 'более', 'менее', 'очень', 'также', 'когда', 'где', 'там', 'тут', 'здесь', 'вот', 'ведь', 'вдруг', 'опять', 'снова', 'потом', 'пока', 'только', 'почти', 'совсем', 'вместе', 'обычно', 'конечно', 'вообще', 'например', 'кроме', 'насчет', 'вроде', 'неужели', 'разве', 'впрочем', 'итак', 'причем', 'притом', 'я', 'ты', 'мы', 'вы', 'он', 'она', 'оно', 'они', 'меня', 'тебя', 'нас', 'вас', 'его', 'ее', 'их', 'мне', 'тебе', 'нам', 'вам', 'ему', 'ей', 'им', 'мой', 'твой', 'наш', 'ваш', 'свой', 'себя', 'который', 'которая', 'которое', 'которые', 'этот', 'эта', 'это', 'эти', 'такой', 'такая', 'такое', 'такие', 'весь', 'вся', 'все', 'все'}
    
    keywords = [(word, freq) for word, freq in word_freq.most_common(50) 
                if word not in stop_words and len(word) > 2]
    return keywords


def suggest_keywords_for_service(service: str) -> list:
    """Предлагает ключевые слова для конкретной услуги."""
    service_lower = service.lower()
    suggestions = []
    
    for category, kws in BASE_KEYWORDS.items():
        for kw in kws:
            if any(word in kw for word in service_lower.split()):
                suggestions.append({"keyword": kw, "category": category})
    
    return suggestions


