def generate_content_plan(competitor_topics: Dict, month: int = None, posts_per_week: int = 4) -> List[Dict]:
    if month is None:
        month = datetime.now().month
    season = SEASONAL_TRIGGERS.get(month, SEASONAL_TRIGGERS[1])

    plan = []
    start_date = datetime(datetime.now().year, month, 1)
    weeks = 4

    for week in range(weeks):
        week_start = start_date + timedelta(weeks=week)
        for day_offset in range(posts_per_week):
            post_date = week_start + timedelta(days=day_offset * 7 // posts_per_week)

            all_types = list(CONTENT_TEMPLATES.keys())
            weights = [3, 2, 2, 2, 1]  # до/после чаще, юмор реже
            content_type = random.choices(all_types[:5], weights=weights, k=1)[0]
            template = CONTENT_TEMPLATES[content_type]

            hook = random.choice(template["хуки"])

            doctor = None
            for d in DOCTORS_FOR_REELS:
                if any(t in content_type for t in d["темы"]) or week % len(DOCTORS_FOR_REELS) == DOCTORS_FOR_REELS.index(d):
                    doctor = d
                    break
            if not doctor:
                doctor = random.choice(DOCTORS_FOR_REELS)

            rubric = None
            if week < len(season["рубрики"]):
                rubric = season["рубрики"][week]
            else:
                rubric = random.choice(season["рубрики"])

            plan.append({
                "дата": post_date.strftime("%d.%m.%Y"),
                "день_недели": ["Пн", "Вт", "Ср", "Чт", "Пт", "Сб", "Вс"][post_date.weekday()],
                "тип": content_type,
                "хук": hook,
                "врач": doctor["имя"],
                "рубрика": rubric,
                "структура": template["структура"],
                "длительность": template["длительность"],
                "сезон": season["тема"],
                "тон": season["тон"],
            })

    return plan


